export const deployBadge = (status: string) => {
  let tone = "badge-ghost";
  if (status === "success") {
    tone = "badge-primary";
  } else if (status === "failed") {
    tone = "badge-error";
  } else if (status === "building" || status === "deploying") {
    tone = "badge-warning";
  }
  return <span class={`badge badge-sm ${tone}`}>{status}</span>;
};
